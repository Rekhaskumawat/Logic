void StrRevX(char ch[] )
{
    char*start = ch;
    char*end = ch;

    char temp = '\0';

    while(*end != '\0')
    {
        end++;
    }
    end-- ;
    
    while(start < end)
    {
        temp = *start ;
        *start = *end;
        *end = temp;

        start++;
        end-- ;
    }

}//end of the StrRevX function

