int main()
{


    int iLength = 0;
    cout<<"Enter the length of Array for integer :-\n";
    cin>>iLength;
    ArrayX<int>*ipobj = new ArrayX<int>(iLength);
    ipobj->Accept();
    ipobj->Reverse();

    delete ipobj;

    return 0;
}

