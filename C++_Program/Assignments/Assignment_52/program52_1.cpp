template <class T>

T multiplication(T No1 , T No2)
{
    T Ans = 0;
    Ans = No1*No2;
    return Ans ;
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//     Entry point function
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue1 = 0 , iValue2 = 0;

    cout<<"Enter  First  Number:-\n";
    cin>>iValue1;
    cout<<"Enter Second Number:-\n";
    cin>>iValue2;

    int iRet = 0;
    iRet = multiplication(iValue1, iValue2);
    cout<<"Multiplication of Number:-"<<iRet<<"\n";
    return 0 ;

}

