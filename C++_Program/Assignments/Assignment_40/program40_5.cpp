void Display(int iNo)
{
    static int iCnt = 0 ;
    static char ch = 'a';
    while (iCnt < iNo)
    {
        printf("%c\t", ch);
        ch++ ;
        iCnt++;
        Display(iNo);
    }
    

}//end of the Display function

